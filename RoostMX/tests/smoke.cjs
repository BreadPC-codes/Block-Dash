// Browser smoke test: node tests/smoke.cjs <outDir>
const { chromium } = require('playwright');
const path = require('path');
const out = process.argv[2] || '.';
const url = process.argv[3] || 'http://localhost:8765/';
(async () => {
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1 });
  const quality = process.argv[4] || 'low';
  await page.addInitScript((q) => {
    try { if (!localStorage.getItem('roostmx.settings.v1')) localStorage.setItem('roostmx.settings.v1', JSON.stringify({ graphics: { quality: q, fullscreen: false, showFps: true } })); } catch (e) {}
  }, quality);
  const logs = [];
  page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(`[${m.type()}] ${m.text()}`); });
  page.on('pageerror', (e) => logs.push('[pageerror] ' + e.message + '\n' + e.stack));
  const t0 = Date.now();
  await page.goto(url);
  await page.waitForSelector('#screen-main.active', { timeout: 120000 });
  console.log('main menu after', ((Date.now() - t0) / 1000).toFixed(1), 's');
  await page.waitForTimeout(1500);
  console.log('menu fps', await page.evaluate(() => window.__roost.fps.value.toFixed(1)));
  await page.screenshot({ path: path.join(out, 's1-menu.png') });
  await page.click('[data-action="play"]');
  await page.waitForTimeout(400);
  await page.screenshot({ path: path.join(out, 's2-play.png') });
  await page.click('[data-mode="free"]');
  await page.click('[data-action="ride"]');
  await page.waitForTimeout(1200);
  await page.screenshot({ path: path.join(out, 's3-ride-start.png') });
  await page.keyboard.down('KeyW');
  await page.waitForTimeout(3500);
  await page.screenshot({ path: path.join(out, 's4-riding.png') });
  await page.keyboard.down('KeyA');
  await page.waitForTimeout(1200);
  await page.screenshot({ path: path.join(out, 's5-turn.png') });
  await page.keyboard.up('KeyA');
  await page.keyboard.up('KeyW');
  const st = await page.evaluate(() => { const g = window.__roost; const p = g.world.physics; return { state: g.state, speed: p.speed, pos: [p.pos.x, p.pos.y, p.pos.z], crashed: p.crashed, reason: p.crashReason, gear: p.engine.gear, fps: g.fps.value, calls: g.renderer.info.render.calls, tris: g.renderer.info.render.triangles }; });
  console.log('state', JSON.stringify(st));
  await page.keyboard.press('KeyC');
  await page.waitForTimeout(600);
  await page.screenshot({ path: path.join(out, 's6-cam2.png') });
  await page.keyboard.press('KeyC');
  await page.waitForTimeout(600);
  await page.screenshot({ path: path.join(out, 's7-helmet.png') });
  await page.keyboard.press('KeyC');
  await page.keyboard.press('KeyC');
  await page.keyboard.press('Escape');
  await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(out, 's8-pause.png') });
  console.log('LOGS:\n' + logs.slice(0, 40).join('\n'));
  await browser.close();
})().catch((e) => { console.error('TEST FAILED', e); process.exit(1); });
