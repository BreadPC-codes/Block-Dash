// End-to-end UI flow test in headless Chromium: node tests/flows.cjs <outDir> [url]
const { chromium } = require('playwright');
const path = require('path');
const out = process.argv[2] || '.';
const url = process.argv[3] || 'http://localhost:8765/';
const fx = (f) => path.join(__dirname, 'fixtures', f);
let failures = 0;
const ok = (c, m) => { console.log((c ? '  ok   ' : '  FAIL ') + m); if (!c) failures++; };
(async () => {
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const logs = [];
  page.on('console', (m) => { if (['error', 'warning'].includes(m.type()) && !/GPU stall|KHR_parallel|ReadPixels/.test(m.text())) logs.push(`[${m.type()}] ${m.text()}`); });
  page.on('pageerror', (e) => logs.push('[pageerror] ' + e.message + ' ' + (e.stack || '').split('\n')[1]));
  await page.addInitScript(() => { try { if (!localStorage.getItem('roostmx.settings.v1')) localStorage.setItem('roostmx.settings.v1', JSON.stringify({ graphics: { quality: 'low', fullscreen: false } })); } catch (e) {} });
  await page.goto(url);
  await page.waitForSelector('#screen-main.active', { timeout: 120000 });
  const G = (fn, arg) => page.evaluate(fn, arg);
  const wait = (ms) => page.waitForTimeout(ms);

  console.log('1) settings');
  await page.click('[data-action="settings:bike"]');
  await wait(300);
  ok(await page.isVisible('#screen-settings.active'), 'settings open on Bike tab');
  // keyboard navigation: down, right adjusts the focused slider
  await page.mouse.move(5, 5);
  await page.hover('#settings-body .set-row:has-text("Steering sensitivity")');
  await page.mouse.move(5, 700);
  const before = await G(() => window.__roost.settings.bike.steerSens);
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('ArrowRight');
  const after = await G(() => window.__roost.settings.bike.steerSens);
  ok(after > before, `steering sensitivity adjusted with keyboard (${before} -> ${after})`);
  ok(await G(() => window.__roost.world.physics.tune.steerSens) === after, 'physics tune updated live');
  await page.click('[data-tab="graphics"]');
  await wait(200);
  await page.click('#settings-body .set-row:has-text("Speed units") button:has-text("MPH")');
  ok(await G(() => window.__roost.settings.graphics.units) === 'mph', 'speed units set to MPH');
  await page.click('[data-tab="audio"]');
  await wait(200);
  await page.screenshot({ path: path.join(out, 'f1-settings-audio.png') });
  await page.click('[data-tab="controls"]');
  await wait(200);
  await page.click('.keybtn >> nth=0');
  await page.keyboard.press('KeyT');
  await wait(200);
  ok(await G(() => window.__roost.settings.controls.keys.throttle[0]) === 'KeyT', 'throttle rebound to T');
  await page.screenshot({ path: path.join(out, 'f2-settings-controls.png') });
  await page.click('button:has-text("Reset keyboard")');
  ok(await G(() => window.__roost.settings.controls.keys.throttle[0]) === 'KeyW', 'keys reset to defaults');
  await page.keyboard.press('Escape');
  await wait(300);
  ok(await page.isVisible('#screen-main.active'), 'Escape returns to main menu');

  console.log('2) track select -> Pine Hollow');
  await page.click('[data-action="tracks"]');
  await wait(400);
  await page.screenshot({ path: path.join(out, 'f3-tracks.png') });
  await page.click('.track-card:has-text("Pine Hollow")');
  await page.waitForSelector('#screen-play.active', { timeout: 120000 });
  ok(await G(() => window.__roost.world.def.id) === 'pinehollow', 'Pine Hollow loaded');

  console.log('3) time trial start');
  await page.click('[data-mode="trial"]');
  await page.click('[data-action="ride"]');
  await wait(300);
  ok(await G(() => window.__roost.state) === 'countdown', 'countdown started');
  ok(await G(() => window.__roost.world.env.gate.target) === 0, 'start gate raised');
  await page.screenshot({ path: path.join(out, 'f4-countdown.png') });
  await page.keyboard.down('KeyW');
  await page.waitForFunction(() => window.__roost.state === 'riding', null, { timeout: 30000 });
  ok(true, 'gate dropped, riding');
  await page.waitForFunction(() => window.__roost.world.timer.lap >= 1, null, { timeout: 60000 }).catch(() => {});
  await page.keyboard.up('KeyW');
  const tt = await G(() => ({ speed: window.__roost.world.physics.speed, lap: window.__roost.world.timer.lap, start: window.__roost.world.timer.lapStart }));
  ok(tt.speed > 3, `moving after the start (${tt.speed.toFixed(1)} m/s)`);
  ok(tt.lap >= 1, 'lap timing started after crossing the line (lap ' + tt.lap + ')');
  await page.screenshot({ path: path.join(out, 'f5-trial-riding.png') });

  console.log('4) crash and reset');
  await G(() => window.__roost.world.physics.crash('Test crash'));
  await wait(1500);
  ok(await page.isVisible('#crash-box'), 'crash overlay shown');
  await page.screenshot({ path: path.join(out, 'f6-crash.png') });
  await page.keyboard.press('KeyR');
  await wait(400);
  ok(await G(() => !window.__roost.world.physics.crashed), 'reset after crash with R');
  ok(await G(() => window.__roost.rider.group.parent === window.__roost.bikeVisual.root), 'rider back on the bike');

  console.log('5) pause -> garage');
  await page.keyboard.press('Escape');
  await wait(300);
  ok(await G(() => window.__roost.state) === 'paused', 'paused');
  const p0 = await G(() => window.__roost.world.physics.pos.z);
  await wait(500);
  ok(await G(() => window.__roost.world.physics.pos.z) === p0, 'physics frozen while paused');
  await page.click('#screen-pause [data-action="garage"]');
  await page.waitForSelector('#screen-garage.active');
  await wait(1200);
  await page.screenshot({ path: path.join(out, 'f7-garage.png') });
  await page.click('#garage-tabs [data-gtab="paint"]');
  await page.click('.swatch[title="blue"]');
  ok(await G(() => window.__roost.settings.bike.color) === '#1f5fd6', 'bike color set to blue');

  console.log('6) import GLB');
  await page.click('#garage-tabs [data-gtab="import"]');
  await page.setInputFiles('#garage-body input[type=file]', fx('test-bike.glb'));
  await page.waitForFunction(() => /Loaded/.test(document.getElementById('garage-status').textContent), null, { timeout: 30000 });
  const st = await page.textContent('#garage-status');
  ok(true, 'GLB loaded: ' + st.slice(0, 120));
  const cfg = await G(() => window.__roost.garage.current.config);
  ok(cfg.comps.frontWheel.length && cfg.comps.rearWheel.length, 'wheels auto-detected');
  ok(cfg.comps.fork.length && cfg.comps.handlebar.length && cfg.comps.swingarm.length, 'fork/handlebar/swingarm auto-detected');
  ok(Math.abs(cfg.scale - 0.01) < 0.002, 'auto-fit scale from centimetres (' + cfg.scale.toFixed(4) + ')');
  await wait(800);
  await page.screenshot({ path: path.join(out, 'f8-imported.png') });
  await page.click('#garage-tabs [data-gtab="parts"]');
  await page.click('button:has-text("Preview motion")');
  await wait(1000);
  await page.screenshot({ path: path.join(out, 'f9-parts.png') });
  await page.click('#garage-tabs [data-gtab="import"]');
  await page.click('button:has-text("Save & use")');
  await page.waitForFunction(() => window.__roost.settings.game.activeBike !== 'procedural', null, { timeout: 15000 });
  ok(true, 'imported bike saved and set active');

  console.log('7) PKZ inspection');
  await page.setInputFiles('#garage-body input[type=file]', fx('test-mod-native.pkz'));
  await page.waitForSelector('.report', { timeout: 15000 });
  await wait(300);
  const rep = await page.textContent('.report');
  ok(/proprietary/i.test(rep) && /\.edf/.test(rep), 'native PKZ reported as unsupported proprietary .edf');
  ok(/How to use a bike from a \.pkz mod/.test(rep), 'conversion guide shown');
  await page.screenshot({ path: path.join(out, 'f10-pkz-report.png') });
  await page.setInputFiles('#garage-body input[type=file]', fx('not-a-zip.pkz'));
  await wait(800);
  ok(/not a standard ZIP/i.test(await page.textContent('.report')), 'non-zip PKZ reported honestly');
  await page.setInputFiles('#garage-body input[type=file]', fx('test-mod-with-glb.pkz'));
  await page.waitForFunction(() => /Loaded/.test(document.getElementById('garage-status').textContent), null, { timeout: 30000 });
  ok(/testbike\.glb/.test(await page.textContent('.report')), 'GLB inside PKZ extracted and loaded');

  console.log('8) ride the imported bike');
  await page.click('#garage-tabs [data-gtab="bikes"]');
  await page.click('button:has-text("Ride this bike")');
  await page.waitForFunction(() => window.__roost.state === 'riding', null, { timeout: 60000 });
  ok(await G(() => window.__roost.bikeVisual.kind) === 'imported', 'riding with the imported bike');
  await page.keyboard.down('KeyW');
  await wait(5000);
  await page.keyboard.up('KeyW');
  await page.screenshot({ path: path.join(out, 'f11-ride-imported.png') });
  ok(await G(() => window.__roost.world.physics.speed) > 2, 'imported bike moves under physics');

  console.log('9) quality change + main menu');
  await page.keyboard.press('Escape');
  await page.click('#screen-pause [data-action="settings:last"]');
  await page.click('[data-tab="graphics"]');
  await page.click('#settings-body .set-row:has-text("Quality preset") button:has-text("Medium")');
  await page.waitForFunction(() => window.__roost.state !== 'loading' && window.__roost.quality === window.__roost.constructor && false || window.__roost.state !== 'loading', null, { timeout: 120000 });
  await wait(2500);
  ok(await G(() => window.__roost.settings.graphics.quality) === 'medium', 'quality set to medium and world rebuilt');
  await page.keyboard.press('Escape');
  await wait(300);
  await page.click('#screen-pause [data-action="mainmenu"]').catch(() => {});
  await wait(800);
  await page.screenshot({ path: path.join(out, 'f12-menu-after.png') });
  console.log('\nLOGS:\n' + logs.slice(0, 30).join('\n'));
  console.log(failures ? `\n${failures} FAILURES` : '\nALL FLOWS OK');
  await browser.close();
})().catch((e) => { console.error('FLOW TEST CRASHED', e); process.exit(1); });
